// Copies the pinned Three.js ESM build (and the OrbitControls addon actually
// imported at runtime) from node_modules into vendor/three/, and regenerates
// vendor/README.md with the exact version and provenance.
//
// The committed vendor/ tree is the runtime source of truth; this script only
// exists so the tree can be audited and regenerated:
//   npm install && npm run vendor
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const version = pkg.dependencies?.three;
if (!version) {
  console.error("vendor: package.json does not pin a three dependency");
  process.exit(1);
}

const require = createRequire(import.meta.url);
let threeDir;
try {
  const entry = require.resolve("three");
  // three's package.json "exports" map hides ./package.json, so locate the
  // package root from the resolved entry path instead.
  for (const needle of ["\\node_modules\\three\\", "/node_modules/three/"]) {
    const i = entry.lastIndexOf(needle);
    if (i >= 0) threeDir = entry.slice(0, i + needle.length);
  }
} catch {
  // ignore, handled below
}
if (!threeDir || !existsSync(join(threeDir, "build"))) {
  console.error("vendor: three is not installed — run `npm install` first");
  process.exit(1);
}

const vendorThree = join(root, "vendor", "three");
rmSync(vendorThree, { recursive: true, force: true });

// three >= r167 splits the ESM build into three.module.js + three.core.js.
const buildFiles = ["three.module.js", "three.core.js"];
mkdirSync(vendorThree, { recursive: true });
for (const file of buildFiles) {
  const src = join(threeDir, "build", file);
  if (existsSync(src)) cpSync(src, join(vendorThree, file));
}
if (!existsSync(join(vendorThree, "three.module.js"))) {
  console.error(`vendor: ${threeDir}/build/three.module.js not found`);
  process.exit(1);
}

const addons = ["controls/OrbitControls.js"];
for (const rel of addons) {
  const src = join(threeDir, "examples", "jsm", rel);
  if (!existsSync(src)) {
    console.error(`vendor: addon ${rel} not found in three@${version}`);
    process.exit(1);
  }
  const dst = join(vendorThree, "addons", rel);
  mkdirSync(dirname(dst), { recursive: true });
  cpSync(src, dst);
}

cpSync(join(threeDir, "LICENSE"), join(vendorThree, "LICENSE"));

const resolved = JSON.parse(readFileSync(join(threeDir, "package.json"), "utf8")).version;
writeFileSync(
  join(root, "vendor", "README.md"),
  `# Vendored Three.js

This directory holds the only Three.js code executed at build/dev/run time.
It is generated by \`scripts/vendor.mjs\` from the version-pinned dependency in
\`package.json\` (locked by \`package-lock.json\`).

- Upstream: https://github.com/mrdoob/three.js
- npm package: three@${resolved} — https://www.npmjs.com/package/three/v/${resolved}
- License: MIT — see \`three/LICENSE\` (full text copied from the package)

Contents (the files actually imported by the app, nothing else):

- \`three/three.module.js\`, \`three/three.core.js\` — the ESM build (\`import ... from "three"\`,
  mapped by the Vite alias in \`vite.config.ts\`).- \`three/addons/controls/OrbitControls.js\` — the single addon used
  (\`import { OrbitControls } from "three/addons/controls/OrbitControls.js"\`).

Regenerate after changing the pinned version:

    npm install
    npm run vendor

\`node_modules\` is never read at runtime and is not committed.
`,
);

console.log(`vendor: copied three@${resolved} ESM build + OrbitControls into vendor/three/`);
